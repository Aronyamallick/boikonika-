// Generates src/styles/tokens.css from the shared design tokens (single source of truth).
import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { cssVariables, typography, radius, motion } = require('@boikonika/shared');

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'styles', 'tokens.css');

const block = (selector, vars) => `${selector} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

const shared = {
  '--bk-font-sans': typography.fontFamily.sans,
  '--bk-font-serif': typography.fontFamily.serif,
  '--bk-font-mono': typography.fontFamily.mono,
  ...Object.fromEntries(Object.entries(radius).map(([k, v]) => [`--bk-radius-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(motion.duration).map(([k, v]) => [`--bk-duration-${k}`, `${v}ms`])),
  '--bk-ease-standard': motion.easing.standard,
  '--bk-ease-emphasized': motion.easing.emphasized,
};

const css =
  '/* Generated by scripts/generate-tokens.mjs from @boikonika/shared — do not edit by hand. */\n' +
  block(':root', { 'color-scheme': 'light', ...shared, ...cssVariables('light') }) +
  block('.dark', { 'color-scheme': 'dark', ...cssVariables('dark') });

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css written (${css.length} bytes)`);
